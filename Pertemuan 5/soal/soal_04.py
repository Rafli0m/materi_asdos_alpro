"""
CERITA SOAL:
Maya membeli 8 buah buku tulis di toko alat tulis. Harga satu buah buku tulis adalah Rp4.500. Maya ingin menghitung total uang yang harus dibayarkan.
"""

# 1. Buat variabel jumlah_buku bernilai 8 dan harga_satuan bernilai 4500
jumlah_buku = 8
harga_satuan = 4500

# 2. Hitung total harga dengan mengalikan kedua variabel tersebut ke dalam variabel total_bayar
total_bayar = jumlah_buku * harga_satuan

# 3. Tampilkan nilai total_bayar ke layar
print(f"Jumlah buku  : {jumlah_buku} buah")
print(f"Harga satuan : Rp{harga_satuan:,}")
print(f"Total bayar  : Rp{total_bayar:,}")

