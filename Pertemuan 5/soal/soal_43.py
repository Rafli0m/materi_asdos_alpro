"""
CERITA SOAL:
Program sains komputer menampilkan deret perpangkatan dua mulai dari 1, 2, 4, 8, hingga batas nilai di bawah 100.
"""

# 1. Inisialisasi variabel nilai = 1
nilai = 1

# 2. Gunakan while nilai < 100
while nilai < 100:
    # 3. Tampilkan nilai saat ini
    print(nilai)
    # 4. Kalikan nilai dengan 2 pada setiap iterasi (nilai = nilai * 2)
    nilai = nilai * 2

