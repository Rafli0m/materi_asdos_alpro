"""
CERITA SOAL:
Pak Rahmat memiliki petak kebun jagung berbentuk persegi dengan panjang sisi 12 meter. Ia ingin menghitung luas kebun tersebut untuk menentukan jumlah pupuk yang dibutuhkan.
"""

# 1. Buat variabel sisi bernilai 12
sisi = 12

# 2. Hitung luas persegi dengan rumus sisi * sisi dan simpan dalam variabel luas
luas = sisi * sisi

# 3. Tampilkan nilai luas ke layar menggunakan fungsi print()
print(f"Panjang sisi kebun : {sisi} meter")
print(f"Luas petak kebun   : {luas} meter persegi")

