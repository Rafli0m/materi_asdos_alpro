"""
CERITA SOAL:
Sebuah proyek kampus direncanakan selesai dalam waktu 3 hari. Mahasiswa ingin mengetahui berapa total jam dan total detik dari durasi tersebut.
"""

# 1. Buat variabel jumlah_hari bernilai 3
jumlah_hari = 3

# 2. Hitung total jam (jumlah_hari * 24) ke dalam variabel total_jam
total_jam = jumlah_hari * 24

# 3. Hitung total detik (total_jam * 3600) ke dalam variabel total_detik
total_detik = total_jam * 3600

# 4. Tampilkan nilai total_jam dan total_detik ke layar
print(f"Jumlah hari : {jumlah_hari} hari")
print(f"Total jam   : {total_jam} jam")
print(f"Total detik : {total_detik} detik")

