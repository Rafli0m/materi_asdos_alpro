"""
CERITA SOAL:
Sebuah roda sepeda anak memiliki jari-jari 14 cm. Pengrajin sepeda ingin menghitung keliling roda menggunakan nilai pendekatan pi 3.14.
"""

# 1. Buat variabel jari_jari bernilai 14.0 dan pi bernilai 3.14
jari_jari = 14.0
pi = 3.14

# 2. Hitung keliling roda dengan rumus 2 * pi * jari_jari ke dalam variabel keliling_roda
keliling_roda = 2 * pi * jari_jari

# 3. Tampilkan nilai keliling_roda ke layar
print(f"Jari-jari roda : {jari_jari} cm")
print(f"Nilai pi       : {pi}")
print(f"Keliling roda  : {keliling_roda} cm")

