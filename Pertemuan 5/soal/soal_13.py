"""
CERITA SOAL:
Sebuah pabrik memproduksi kotak sepatu berbentuk balok dengan panjang 30 cm, lebar 18 cm, dan tinggi 12 cm.
"""

# 1. Buat variabel panjang bernilai 30, lebar bernilai 18, dan tinggi bernilai 12
panjang = 30
lebar = 18
tinggi = 12

# 2. Hitung volume balok dengan rumus panjang * lebar * tinggi ke dalam variabel volume_kotak
volume_kotak = panjang * lebar * tinggi

# 3. Tampilkan nilai volume_kotak ke layar
print(f"Panjang balok : {panjang} cm")
print(f"Lebar balok   : {lebar} cm")
print(f"Tinggi balok  : {tinggi} cm")
print(f"Volume kotak  : {volume_kotak} cm3")

