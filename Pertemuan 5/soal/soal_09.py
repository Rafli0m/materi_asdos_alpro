"""
CERITA SOAL:
Paman memanen 50 kg jeruk dan ingin membaginya secara merata ke dalam 4 keranjang buah tanpa menyisakan jeruk.
"""

# 1. Buat variabel total_panen bernilai 50.0 dan jumlah_keranjang bernilai 4
total_panen = 50.0
jumlah_keranjang = 4

# 2. Hitung berat jeruk per keranjang menggunakan pembagian riil (/) ke dalam variabel berat_per_keranjang
berat_per_keranjang = total_panen / jumlah_keranjang

# 3. Tampilkan nilai berat_per_keranjang ke layar
print(f"Total panen jeruk   : {total_panen} kg")
print(f"Jumlah keranjang    : {jumlah_keranjang}")
print(f"Berat per keranjang : {berat_per_keranjang} kg")

