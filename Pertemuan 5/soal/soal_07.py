"""
CERITA SOAL:
Seorang nelayan ingin mengganti kain layar perahunya yang berbentuk segitiga dengan ukuran alas 4 meter dan tinggi 6 meter.
"""

# 1. Buat variabel alas bernilai 4.0 dan tinggi bernilai 6.0
alas = 4.0
tinggi = 6.0

# 2. Hitung luas layar dengan rumus 0.5 * alas * tinggi ke dalam variabel luas_segitiga
luas_segitiga = 0.5 * alas * tinggi

# 3. Tampilkan nilai luas_segitiga ke layar
print(f"Alas layar   : {alas} meter")
print(f"Tinggi layar : {tinggi} meter")
print(f"Luas layar   : {luas_segitiga} meter persegi")

