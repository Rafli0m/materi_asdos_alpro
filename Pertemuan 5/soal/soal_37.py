"""
CERITA SOAL:
Mahasiswa diminta membuat program yang menampilkan deret bilangan ganjil positif dari angka 1 sampai kurang dari 20.
"""

# 1. Inisialisasi variabel bilangan = 1
bilangan = 1

# 2. Gunakan perulangan while bilangan < 20
while bilangan < 20:
    # 3. Tampilkan nilai bilangan ke layar
    print(bilangan)
    # 4. Tambahkan nilai bilangan sebanyak 2 pada setiap iterasi
    bilangan += 2

