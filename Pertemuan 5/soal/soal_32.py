"""
CERITA SOAL:
Seorang anak ingin mencatat bilangan kelipatan 4 mulai dari angka 4 hingga batas maksimal 40.
"""

# 1. Inisialisasi variabel angka = 4
angka = 4

# 2. Gunakan perulangan while angka <= 40 untuk mencetak nilai angka
while angka <= 40:
    print(angka)
    # 3. Tambahkan nilai angka sebesar 4 pada setiap iterasi
    angka += 4

