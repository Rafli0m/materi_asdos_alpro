"""
CERITA SOAL:
Andi berumur 21 tahun dan adiknya berumur 14 tahun. Mereka ingin mengetahui berapa selisih umur di antara keduanya.
"""

# 1. Buat variabel umur_kakak bernilai 21 dan umur_adik bernilai 14
umur_kakak = 21
umur_adik = 14

# 2. Hitung selisih umur dengan rumus umur_kakak - umur_adik ke dalam variabel selisih_umur
selisih_umur = umur_kakak - umur_adik

# 3. Tampilkan nilai selisih_umur ke layar
print(f"Umur kakak   : {umur_kakak} tahun")
print(f"Umur adik    : {umur_adik} tahun")
print(f"Selisih umur : {selisih_umur} tahun")

