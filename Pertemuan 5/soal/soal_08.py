"""
CERITA SOAL:
Sebuah bak mandi penampungan air berbentuk kubus sempurna dengan panjang rusuk 90 cm. Pemilik rumah ingin menghitung volume tampung bak tersebut.
"""

# 1. Buat variabel rusuk bernilai 90
rusuk = 90

# 2. Hitung volume dengan operasi pangkat tiga (rusuk ** 3) ke dalam variabel volume_kubus
volume_kubus = rusuk ** 3

# 3. Tampilkan nilai volume_kubus ke layar
print(f"Panjang rusuk : {rusuk} cm")
print(f"Volume kubus  : {volume_kubus} cm3")

