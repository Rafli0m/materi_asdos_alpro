# 1. Buat variabel panjang bernilai 120 dan lebar bernilai 60
panjang = 120
lebar = 60

# 2. Hitung keliling meja dengan rumus 2 * (panjang + lebar) dan simpan dalam variabel keliling
keliling = 2 * (panjang + lebar)

# 3. Tampilkan nilai keliling ke layar
print(f"Panjang meja  : {panjang} cm")
print(f"Lebar meja    : {lebar} cm")
print(f"Keliling meja : {keliling} cm")

